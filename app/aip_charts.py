@dataclass(frozen=True)
class Passung:
    """Zwei Rechtecke: das Blatt (danach wird platziert) und das Kartenfeld (danach wird
    geschaltet und geprueft)."""
    nord: float
    sued: float
    west: float
    ost: float
    feld_nord: float
    feld_sued: float
    feld_west: float
    feld_ost: float
    rahmen_px: str          # "links,oben,rechts,unten"
    tick_px_lat: float
    tick_px_lon: float


# Breitenabweichung, ab der die cos-Probe durchfaellt. Ueber 356 gemessene Karten lag der
# Fehler im Median bei 0,085 Grad, der 90-Prozent-Wert bei 0,167, das Maximum bei 0,354 --
# die Toleranz ist also in-sample gewaehlt, mit 13 Prozent Luft.
GEGENPROBE_TOLERANZ = 0.4
# Deutschland liegt zwischen 47,3 und 55,0 Grad. Ein Verhaeltnis ausserhalb dieses Bandes
# ist Unsinn und wird frueh verworfen -- das kostet nichts und nimmt der Suche Freiheit.
_V_MIN, _V_MAX = 0.57, 0.68
# Bei 22 von 356 Karten tragen die Achsen verschiedene Tick-Einheiten. Jeder Kandidat mehr
# hebt die Zufallstrefferquote um rund einen halben Prozentpunkt (Spec 3.2).
_ACHSEN_VIELFACHE = (1.0, 2.0, 0.5)
# Mindestens so viele lesbare Stuetzstellen je Achse.
#
# Drei waeren schoener -- erst ab dreien gibt es Residuen und damit Pruefung (3). Viele
# Blaetter tragen aber nur drei Breiten-Ticks; faellt einer aus, bleiben zwei, und an dieser
# Huerde scheiterten 18 von 100 gemessenen Blaettern.
#
# Zwei sind vertretbar, weil Pruefung (2) unabhaengig davon greift: Die aus den Zahlen
# gewonnene Skala muss zum gemessenen Rasterabstand passen. Ist EINE der beiden Zahlen falsch
# gelesen, ist die Skala falsch und die Pruefung schlaegt an. Nur ein systematischer Fehler
# in BEIDEN bliebe unentdeckt -- und der ist ohnehin die bekannte Grenze der Kette (Spec 3.1).
_MIND_STUETZSTELLEN = 2
# Ab dieser Zahl greift zusaetzlich die Residuenpruefung. Darunter traegt Pruefung (2) allein.
_MIND_FUER_RESIDUEN = 3
# Groesstes zulaessiges Residuum in Pixeln. Ein Ziffernfehler von einer Bogenminute erzeugt
# bei 219 px je Minute rund 146 px -- die Schwelle ist also sehr scharf.
_MAX_RESIDUUM_PX = 2.0


def ausgleichsgerade(paare: list[tuple[float, float]]
                     ) -> tuple[float, float, float] | None:
    """Gerade Grad = m*Pixel + b ueber ALLE Stuetzstellen, dazu das groesste Residuum.

    Nur die erste und letzte Stuetzstelle zu nehmen, waere billiger und deutlich schlechter:
    Ein einzelner Ziffernfehler bliebe dann unbemerkt und wuerde bei der Verlaengerung auf
    das ganze Blatt noch verstaerkt.
    """
    n = len(paare)
    if n < 2:
        return None
    sx = sum(p for p, _ in paare)
    sy = sum(g for _, g in paare)
    sxx = sum(p * p for p, _ in paare)
    sxy = sum(p * g for p, g in paare)
    nenner = n * sxx - sx * sx
    if abs(nenner) < 1e-12:
        return None
    m = (n * sxy - sx * sy) / nenner
    b = (sy - m * sx) / n
    res = max(abs(g - (m * p + b)) for p, g in paare)
    return m, b, res


def passung_rechnen(im, arp_lat: float, arp_lon: float) -> Passung | None:
    """WGS84-Grenzen von Blatt und Kartenfeld. None, sobald eine Pruefung durchfaellt.

    Vier Pruefungen, weil eine nicht reicht (Spec 3.1): Die cos-Probe kennt nur das
    Verhaeltnis der Tickabstaende, die Grenzen entstehen aber aus den gelesenen Zahlen --
    gegen einen Lesefehler ist sie blind.

    **Bekannte Grenze:** Ein SYSTEMATISCHER Offset (alle Stuetzstellen um denselben Betrag
    verschoben) laesst das Residuum null; es bleibt nur der Lagetest, und der laesst rund
    2,9 km durch. Da jede Zahl an ihrem eigenen Tick gelesen wird, ist das unplausibel --
    ausgeschlossen ist es nicht.
    """
    rahmen = rahmen_finden(im)
    if rahmen is None:
        return None
    ty, tx = tick_positionen(im, rahmen)
    dy, _ny, _ay = raster(ty)
    dx, _nx, _ax = raster(tx)
    if not dy or not dx:
        return None

    # (1) cos-Probe -- Vorpruefung der Skala.
    bester = None
    for k in _ACHSEN_VIELFACHE:
        v = (dx * k) / dy
        if not (_V_MIN < v < _V_MAX):
            continue
        fehler = abs(math.degrees(math.acos(v)) - arp_lat)
        if bester is None or fehler < bester:
            bester = fehler
    if bester is None or bester > GEGENPROBE_TOLERANZ:
        logger.info("AIP: cos-Probe nicht bestanden")
        return None

    lat_paare = beschriftung_lesen(im, rahmen, ty, "y")
    lon_paare = beschriftung_lesen(im, rahmen, tx, "x")
    if len(lat_paare) < _MIND_STUETZSTELLEN or len(lon_paare) < _MIND_STUETZSTELLEN:
        logger.info("AIP: zu wenige lesbare Stuetzstellen (%d/%d)",
                    len(lat_paare), len(lon_paare))
        return None

    lat_g = ausgleichsgerade(lat_paare)
    lon_g = ausgleichsgerade(lon_paare)
    if lat_g is None or lon_g is None:
        return None
    m_lat, b_lat, res_lat = lat_g
    m_lon, b_lon, res_lon = lon_g
    if abs(m_lat) < 1e-12 or abs(m_lon) < 1e-12:
        return None

    # (2) Passt die aus den ZAHLEN gewonnene Skala zum gemessenen Rasterabstand? Ein Tick ist
    # eine ganze Bogenminute (oder ein Vielfaches); 1/(60*|m|) ist also der Pixelabstand, den
    # die gelesenen Werte behaupten. Weicht er ab, ist eine der beiden Groessen falsch.
    for m, d in ((m_lat, dy), (m_lon, dx)):
        behauptet = 1.0 / (60.0 * abs(m))
        vielfaches = round(d / behauptet) if behauptet > 0 else 0
        if vielfaches < 1 or abs(d - vielfaches * behauptet) > _MAX_RESIDUUM_PX:
            logger.info("AIP: gelesene Skala passt nicht zum Rasterabstand")
            return None

    # (3) Residuen, in Pixel umgerechnet -- ein einzelner Ziffernfehler faellt hier auf.
    # Bei nur zwei Stuetzstellen liegt die Gerade zwangslaeufig exakt; dort traegt Pruefung
    # (2) allein.
    if len(lat_paare) >= _MIND_FUER_RESIDUEN and res_lat / abs(m_lat) > _MAX_RESIDUUM_PX:
        logger.info("AIP: Breiten-Stuetzstellen nicht auf einer Geraden")
        return None
    if len(lon_paare) >= _MIND_FUER_RESIDUEN and res_lon / abs(m_lon) > _MAX_RESIDUUM_PX:
        logger.info("AIP: Laengen-Stuetzstellen nicht auf einer Geraden")
        return None

    # Genordet heisst: nach unten nimmt die Breite AB, nach rechts die Laenge ZU. Trifft das
    # nicht zu, ist etwas grundlegend falsch gelesen. Das still zu normalisieren wuerde das
    # Blatt gespiegelt auflegen, ohne dass ein Test anschlaegt.
    if m_lat > 0 or m_lon < 0:
        logger.info("AIP: Blatt scheint nicht genordet -- verworfen")
        return None

    breite_px, hoehe_px = im.size
    nord, sued = b_lat, m_lat * hoehe_px + b_lat
    west, ost = b_lon, m_lon * breite_px + b_lon
    feld_nord, feld_sued = m_lat * rahmen.oben + b_lat, m_lat * rahmen.unten + b_lat
    feld_west, feld_ost = m_lon * rahmen.links + b_lon, m_lon * rahmen.rechts + b_lon

    # (4) Lagetest gegen das KARTENFELD, nicht gegen das Blatt.
    if not (feld_sued < arp_lat < feld_nord and feld_west < arp_lon < feld_ost):
        logger.info("AIP: Flugplatz liegt nicht im Kartenfeld")
        return None

    return Passung(
        nord=nord, sued=sued, west=west, ost=ost,
        feld_nord=feld_nord, feld_sued=feld_sued, feld_west=feld_west, feld_ost=feld_ost,
        rahmen_px=f"{rahmen.links:.1f},{rahmen.oben:.1f},{rahmen.rechts:.1f},{rahmen.unten:.1f}",
        tick_px_lat=dy, tick_px_lon=dx,
    )


# ---------------------------------------------------------------------------
# AIRAC-Nachlauf und Ablage
# ---------------------------------------------------------------------------
_TOLERANZ_RAHMEN_PX = 2.0
# Schaerfer als beim Rahmen: 2 px auf 219 sind 0,9 Prozent und entsprechen ueber
# dphi/dv = 1/sin(phi) rund 0,5 Grad Breite -- mehr als die cos-Probe zulaesst.
_TOLERANZ_RASTER_PX = 0.5


def geometrie_gleich(alt: dict, neu: "Passung") -> bool:
    """Traegt das neue Blatt denselben Ausschnitt wie das alte?

    Wenn ja, hat sich nur der Inhalt geaendert (Hindernis ergaenzt, Frequenz korrigiert) und
    die Passung bleibt gueltig -- auch eine von Hand gesetzte.
    """
    try:
        a = [float(v) for v in str(alt["rahmen_px"]).split(",")]
        b = [float(v) for v in neu.rahmen_px.split(",")]
        lat_alt, lon_alt = float(alt["tick_px_lat"]), float(alt["tick_px_lon"])
    except (KeyError, TypeError, ValueError):
        return False
    if len(a) != 4 or len(b) != 4:
        return False
    if any(abs(x - y) > _TOLERANZ_RAHMEN_PX for x, y in zip(a, b)):
        return False
    return (abs(lat_alt - neu.tick_px_lat) <= _TOLERANZ_RASTER_PX
            and abs(lon_alt - neu.tick_px_lon) <= _TOLERANZ_RASTER_PX)


def blatt_schreiben(pfad, roh: bytes) -> None:
    """Blatt atomar ablegen: erst daneben, dann umbenennen.

    Sonst liefert FileResponse mitten im Austausch ein abgeschnittenes PNG aus.
    """
    ziel = Path(pfad)
    ziel.parent.mkdir(parents=True, exist_ok=True)
    tmp = ziel.with_suffix(ziel.suffix + ".tmp")
    tmp.write_bytes(roh)
    os.replace(tmp, ziel)


def blatt_pfad(db_path: str, icao: str) -> "Path":
    """Wo das Blatt liegt. Neben der Datenbank, im Volume -- so ueberlebt es den Container."""
    return Path(db_path).parent / "aip" / f"{(icao or '').strip().upper()}.png"


def blatt_beschaffen(url: str, arp_lat: float, arp_lon: float,
                     hole) -> tuple[bytes | None, "Passung | None", str | None]:
    """Blatt und Passung zu einem Kartenlink besorgen.

    ``hole`` ist eine Funktion URL -> HTML. Sie wird hereingereicht, damit diese Funktion
    ohne Netz pruefbar bleibt; das Skript und der Poller geben ihren httpx-Aufruf mit.

    Traegt die verlinkte Seite keinen Kartenrahmen, werden die uebrigen Seiten desselben
    Kapitels geprueft -- bei EDAZ oeffnet der Link die Textseite "VFR-Flugverfahren", die
    Sichtflugkarte ist die vierte Seite. Das betrifft 28 von 446 Karten.

    Fehler beim Abruf werden NICHT geschluckt: Der Aufrufer muss unterscheiden koennen
    zwischen "Karte passt nicht" und "Netz war weg" -- im zweiten Fall darf er die
    bestehende Karte nicht entwerten.
    """
    from PIL import Image
    import io

    erste = hole(url)
    ziel = airac_url(erste, url) or url
    airac = airac_kennung(ziel)
    html = hole(ziel) if ziel != url else erste

    def versuche(seiten_html: str) -> tuple[bytes | None, "Passung | None"]:
        roh = bild_aus_html(seiten_html)
        if roh is None:
            return None, None
        try:
            im = Image.open(io.BytesIO(roh)).convert("L")
        except Exception:
            return None, None
        return roh, passung_rechnen(im, arp_lat, arp_lon)

    roh, passung = versuche(html)
    if passung is not None:
        return roh, passung, airac

    for kapitel in kapitel_links(html, ziel):
        try:
            weiter = hole(kapitel)
        except Exception:
            logger.info("AIP: Kapitelseite %s nicht erreichbar", kapitel)
            continue
        for seite in kapitelseiten(weiter, kapitel):
            if seite == ziel:
                continue
            try:
                roh2, passung2 = versuche(hole(seite))
            except Exception:
                continue
            if passung2 is not None:
                return roh2, passung2, airac
    return roh, None, airac


def handpassung(breite_px: int, hoehe_px: int,
                links_px: float, oben_px: float, rechts_px: float, unten_px: float,
                feld_nord: float, feld_sued: float,
                feld_west: float, feld_ost: float) -> "Passung | None":
    """Passung aus zwei von Hand geklickten Rahmenecken.

    **Der Handpfad rechnet genauso weiter wie die Automatik.** Aus den zwei Rahmenpunkten
    wird die lineare Abbildung gebildet und auf die Blattkanten verlaengert; erst das ergibt
    ``nord/sued/west/ost``. Die geklickten Werte direkt als Blattgrenzen abzulegen waere
    falsch -- beim Standardblatt wuerde ein 875x1240-Bild in einen 685x685-Rahmen gequetscht,
    rund 45 Prozent Massstabsfehler senkrecht. Das betraefe ausgerechnet die Karten, denen
    man am meisten vertraut, weil ein Mensch sie gesetzt hat.

    None, wenn die Angaben nicht zusammenpassen.
    """
    if not (0 <= links_px < rechts_px <= breite_px and 0 <= oben_px < unten_px <= hoehe_px):
        return None
    if not (feld_sued < feld_nord and feld_west < feld_ost):
        return None
    grad_je_y = (feld_sued - feld_nord) / (unten_px - oben_px)     # negativ: nach unten Sueden
    grad_je_x = (feld_ost - feld_west) / (rechts_px - links_px)
    return Passung(
        nord=feld_nord + (0 - oben_px) * grad_je_y,
        sued=feld_nord + (hoehe_px - oben_px) * grad_je_y,
        west=feld_west + (0 - links_px) * grad_je_x,
        ost=feld_west + (breite_px - links_px) * grad_je_x,
        feld_nord=feld_nord, feld_sued=feld_sued,
        feld_west=feld_west, feld_ost=feld_ost,
        rahmen_px=f"{links_px:.1f},{oben_px:.1f},{rechts_px:.1f},{unten_px:.1f}",
        tick_px_lat=0.0, tick_px_lon=0.0,
    )
